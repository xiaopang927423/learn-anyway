const {app,BrowserWindow}=require('electron')
const path=require('node:path'),fs=require('node:fs'),assert=require('node:assert/strict')
app.disableHardwareAcceleration()
app.whenReady().then(async()=>{
 const out=path.resolve(__dirname,'../dist/website-preview');fs.mkdirSync(out,{recursive:true})
 const win=new BrowserWindow({width:1440,height:1050,show:false,webPreferences:{offscreen:false,contextIsolation:true,nodeIntegration:false}})
 await win.loadFile(path.resolve(__dirname,'../website/index.html'))
 await win.webContents.executeJavaScript("localStorage.setItem('wordmate-site-language','zh');location.reload()")
 await new Promise(resolve=>win.webContents.once('did-finish-load',resolve))
 assert.equal(await win.webContents.executeJavaScript('document.documentElement.lang'),'zh-CN')
 assert.ok((await win.webContents.executeJavaScript('document.querySelector("h1").textContent')).includes('真正记住'))
 await win.webContents.executeJavaScript("document.querySelector('[data-demo=english]').click()")
 assert.equal(await win.webContents.executeJavaScript('document.getElementById("demoOutput").textContent'),'I want to eat breakfast')
 await win.webContents.executeJavaScript("document.querySelector('[data-demo=mixed]').click()")
 fs.writeFileSync(path.join(out,'desktop-zh.png'),(await win.webContents.capturePage()).toPNG())
 await win.webContents.executeJavaScript('document.getElementById("language").click()')
 assert.equal(await win.webContents.executeJavaScript('document.documentElement.lang'),'en')
 assert.ok((await win.webContents.executeJavaScript('document.querySelector("h1").textContent')).includes('Read. Write.'))
 await win.webContents.executeJavaScript("document.querySelector('[data-demo=chinese]').click()")
 assert.equal(await win.webContents.executeJavaScript('document.getElementById("demoOutput").textContent'),'星河')
 assert.ok((await win.webContents.executeJavaScript('document.getElementById("demoDetail").textContent')).includes('Number keys'))
 await win.webContents.executeJavaScript("document.querySelector('[data-tour-module=browser]').click()")
 assert.equal(await win.webContents.executeJavaScript('WordMateTour.getState().module'),'browser')
 await win.webContents.executeJavaScript("document.getElementById('tourNext').click()")
 assert.ok((await win.webContents.executeJavaScript("document.getElementById('tourCanvas').textContent")).includes('小习惯'))
 await win.webContents.executeJavaScript("document.getElementById('tourPlay').click()")
 assert.equal(await win.webContents.executeJavaScript('WordMateTour.getState().playing'),true)
 await win.webContents.executeJavaScript("document.getElementById('tourPlay').click()")
 assert.equal(await win.webContents.executeJavaScript('WordMateTour.getState().playing'),false)
 await win.webContents.executeJavaScript("document.querySelector('[data-tour-module=notebook]').click();document.getElementById('tourNext').click();document.getElementById('tourNext').click();document.getElementById('tourNext').click()")
 assert.ok((await win.webContents.executeJavaScript("document.getElementById('tourTitle').textContent")).includes('spelling'))
 assert.equal(await win.webContents.executeJavaScript("/实验|experimental/i.test(document.body.innerText)"),false)
 await win.webContents.executeJavaScript("document.getElementById('tourPlay').click()")
 await new Promise(resolve=>setTimeout(resolve,3700))
 assert.equal(await win.webContents.executeJavaScript('WordMateTour.getState().step'),4)
 await win.webContents.executeJavaScript("document.getElementById('tourPlay').click();document.documentElement.style.scrollBehavior='auto';document.getElementById('how').scrollIntoView()")
 fs.writeFileSync(path.join(out,'tour-en.png'),(await win.webContents.capturePage()).toPNG())
 await win.webContents.executeJavaScript("document.getElementById('language').click();document.querySelector('[data-tour-module=browser]').click();document.getElementById('tourNext').click();document.documentElement.style.scrollBehavior='auto';document.getElementById('how').scrollIntoView()")
 fs.writeFileSync(path.join(out,'tour-zh.png'),(await win.webContents.capturePage()).toPNG())
 await win.webContents.executeJavaScript("document.getElementById('language').click();window.scrollTo(0,0)")
 fs.writeFileSync(path.join(out,'desktop-en.png'),(await win.webContents.capturePage()).toPNG())
 for(const width of [390,320]){
  win.setContentSize(width,900)
  await win.webContents.executeJavaScript('window.scrollTo(0,0)')
  const measure=await win.webContents.executeJavaScript('({scroll:document.documentElement.scrollWidth,width:window.innerWidth})')
  assert.ok(measure.scroll<=measure.width,JSON.stringify(measure))
  if(width===390)fs.writeFileSync(path.join(out,'mobile-en.png'),(await win.webContents.capturePage()).toPNG())
 }
 assert.equal(await win.webContents.executeJavaScript("[...document.querySelectorAll('[data-i18n]')].filter(el=>el.textContent.includes('undefined')).length"),0)
 console.log('WEBSITE_OK Chinese/English switch, demos, persistence, 390px/320px widths; '+out)
 win.destroy();app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
